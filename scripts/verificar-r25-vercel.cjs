/** Offline acceptance gate for the Vercel proposal package. Uses only Node built-ins. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const from = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const exists = relative => fs.existsSync(path.join(root, relative));
let count = 0;
const check = (condition, label) => { assert.ok(condition, label); count += 1; };

const pkg = JSON.parse(from('package.json'));
const vercel = JSON.parse(from('vercel.json'));
const shell = from('src/jarcar-v4/Shell.tsx');
const css = from('src/jarcar-v4/r25-pinned-header.css');
const main = from('src/jarcar-v4/main.tsx');
const vite = from('vite.config.ts');
const html = from('index.html');
const bat = from('INICIAR_JARCAR.bat');
const checklist = from('VALIDAR_VERCEL.bat');

check(pkg.name.includes('r25'), 'Nombre versión R25');
check(pkg.scripts.build === 'tsc --noEmit && vite build', 'Build con tipos y Vite');
check(pkg.scripts.dev.includes('--strictPort'), 'Puerto local estricto');
check(pkg.scripts.dev.includes('4631'), 'Puerto local nuevo');
check(pkg.engines.node.includes('20.19'), 'Rango Node compatible');
check(vercel.framework === 'vite', 'Framework declarado Vite');
check(vercel.outputDirectory === 'dist', 'Salida dist');
check(vercel.buildCommand === 'npm run build', 'Vercel compila el proyecto');
check(vercel.redirects.some(r => r.source === '/' && r.destination === '/jarcar'), 'Ruta inicial redirige a /jarcar');
check(vercel.rewrites.some(r => r.source === '/jarcar' && r.destination === '/index.html'), 'SPA raíz /jarcar');
check(vercel.rewrites.some(r => r.source === '/jarcar/:path*' && r.destination === '/index.html'), 'SPA rutas anidadas incluidas fichas');
check(!vercel.rewrites.some(r => r.source.startsWith('/assets')), 'Los assets no se reescriben');
check(vercel.headers.flatMap(h => h.headers ?? []).some(h => h.key.toLowerCase() === 'x-robots-tag' && h.value.includes('noindex')), 'No indexación de propuesta');
check(shell.includes('className="ja-header ja-header-pinned"'), 'Header utiliza clase fija');
check(shell.includes('className="ja-header-spacer"'), 'Espaciador evita superposición');
check(shell.includes("import './r25-pinned-header.css'"), 'Styles de header importados');
check(css.includes('position: fixed !important'), 'Header fijado en viewport');
check(css.includes('width: 100%'), 'Header ocupa todo el ancho');
check(css.includes('var(--site-header-h)'), 'Espaciador tiene tamaño del navbar');
check(css.includes('.ja-nav-dialog { z-index: 501'), 'Menú abre sobre el navbar');
check(css.includes('env(safe-area-inset-top'), 'Compatibilidad safe area');
check(css.includes('@media print'), 'No hay espaciador durante impresión');
check(html.includes('noindex, nofollow'), 'Meta robots privada');
check(html.includes('R25-VERCEL-PROPOSAL'), 'Metadatos R25');
check(main.includes('<BrowserRouter'), 'React Router en cliente');
check(main.includes('path="inventario/:demoId"'), 'Ruta de fichas accesible');
check(main.includes('path="jarcar-motors"'), 'Ruta Nosotros accesible');
check(main.includes("window.location.pathname === '/'"), 'Ruta raíz también funciona localmente');
check(vite.includes("appType: 'spa'"), 'Vite SPA');
check(!vite.includes('proxy:'), 'Sin proxy backend');
check(bat.includes('4631'), 'BAT apunta a puerto correcto');
check(checklist.includes('npm run build'), 'BAT verifica build');
check(checklist.includes('verificar-r25-vercel.cjs'), 'BAT valida Vercel');
check(exists('.nvmrc'), 'Node de Vercel documentado');
check(from('.nvmrc').trim() === '22', 'Node 22 por defecto');
check(exists('.gitignore'), 'Archivo .gitignore');
check(exists('public/jarcar-v4/mark.svg'), 'Marca de Jarcar');
check(exists('public/jarcar-v4/design/story-intelligent-choice.webp'), 'Visual de landing');
check(exists('public/jarcar-v4/design/about-jarcar-collection.webp'), 'Visual de Nosotros');
check(exists('public/jarcar-v3/vehicles/ford-f150-raptor-2019-01-1280.webp'), 'Fotografías originales de catálogo');
check(exists('GUIA_DESPLIEGUE_VERCEL.md'), 'Guía de despliegue');
check(exists('PROPUESTA_PARA_JARCAR.md'), 'Mensaje para propuesta');
check(exists('src/jarcar-v4/r24-home-mobile.css'), 'Landing móvil conservada');
check(exists('src/jarcar-v4/r23-detail.css'), 'Ficha R23 conservada');

const imageDir = path.join(root, 'public/jarcar-v3/vehicles');
const webps = fs.readdirSync(imageDir).filter(file => file.endsWith('.webp'));
check(webps.length === 445, `445 variantes fotográficas: se encontraron ${webps.length}`);
const assets = ['public/jarcar-v4/mark.svg', 'src/jarcar-v4/Shell.tsx', 'src/jarcar-v4/Home.tsx', 'src/jarcar-v4/Catalog.tsx', 'src/jarcar-v4/Detail.tsx'];
for (const filename of assets) check(fs.statSync(path.join(root, filename)).size > 100, `Archivo con contenido ${filename}`);

console.log(`R25 VERCEL / NAVBAR: ${count} verificaciones offline PASS`);
console.log('IMPORTANTE: este gate no sustituye a npm run build ni a la prueba real en Vercel.');
